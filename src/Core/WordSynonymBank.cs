    private static readonly Dictionary<string, List<SynonymUsageGroup>> Lookup = BuildLookup();

    private static Dictionary<string, List<SynonymUsageGroup>> BuildLookup()
    {
        var map = new Dictionary<string, List<SynonymUsageGroup>>(StringComparer.OrdinalIgnoreCase);
        foreach (var group in Groups)
        {
            foreach (var member in group.Members)
            {
                if (!map.TryGetValue(member.Word, out var list))
                {
                    list = [];
                    map[member.Word] = list;
                }
                list.Add(group);
            }
        }
        return map;
    }

    public static IReadOnlyList<string> GetSiblings(string word)
    {
        if (string.IsNullOrWhiteSpace(word) || !Lookup.TryGetValue(word.Trim(), out var groups))
            return [];

        var result = new List<string>();
        var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase) { word.Trim() };
        foreach (var group in groups)
        {
            foreach (var member in group.Members)
            {
                if (seen.Add(member.Word))
                    result.Add(member.Word);
            }
        }
        return result;
    }

    public static (SynonymUsageGroup Group, SynonymUsageNote Target, SynonymUsageNote Candidate)? FindPair(string targetWord, string candidateWord)
    {
        if (string.IsNullOrWhiteSpace(targetWord) || string.IsNullOrWhiteSpace(candidateWord))
            return null;
        if (!Lookup.TryGetValue(targetWord.Trim(), out var groups))
            return null;

        foreach (var group in groups)
        {
            var cand = group.Members.FirstOrDefault(m => m.Word.Equals(candidateWord.Trim(), StringComparison.OrdinalIgnoreCase));
            if (cand == null) continue;
            var target = group.Members.FirstOrDefault(m => m.Word.Equals(targetWord.Trim(), StringComparison.OrdinalIgnoreCase));
            if (target != null)
                return (group, target, cand);
        }
        return null;
    }
